const withTint = ({ tint, ...product }) => {
  const [background, accent] = tints[tint]
  return { ...product, background, accent }
}

// Category slug → products
export const categoryProducts = Object.fromEntries(
  Object.entries(catalog).map(([slug, products]) => [slug, products.map(withTint)]),
)

// Explore page rows: each category's established products.
export const productSections = browseCategories.map((category) => ({
  slug: category.slug,
  title: category.name,
  to: `/categories/${category.slug}`,
  products: categoryProducts[category.slug].filter((product) => !product.isNew),
}))
